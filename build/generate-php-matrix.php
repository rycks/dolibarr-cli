<?php

declare(strict_types=1);

/*
 * Regenerate server/src/Php/DeclaredMatrix.php from the Dolibarr sources: the PHP range that
 * htdocs/install/check.php of every released version x.y.z declares.
 *
 *   php build/generate-php-matrix.php [--repo=/home/groups/devs/code/dolibarr-git]
 *
 * Consecutive versions with the same values are merged: the matrix gives, for each first
 * version of a range, the minimum refused below (blocking), the minimum advised and the
 * maximum declared (empty when check.php declares none).
 */

$options = getopt('', ['repo::']);
$repo = rtrim((string) ($options['repo'] ?? '/home/groups/devs/code/dolibarr-git'), '/');
$target = dirname(__DIR__).'/server/src/Php/DeclaredMatrix.php';

$git = static function (array $args) use ($repo): string {
    $command = 'git -C '.escapeshellarg($repo).' '.implode(' ', array_map('escapeshellarg', $args)).' 2>/dev/null';
    $output = shell_exec($command);

    return is_string($output) ? $output : '';
};

$tags = array_values(array_filter(
    array_map('trim', explode("\n", $git(['tag', '--list']))),
    static fn (string $tag): bool => 1 === preg_match('/^\d+\.\d+\.\d+$/', $tag) && version_compare($tag, '6.0.0', '>=')
));
usort($tags, 'version_compare');
if ([] === $tags) {
    fwrite(STDERR, "No Dolibarr release tag found in {$repo}\n");
    exit(1);
}

$read = static function (string $code, string $variable): string {
    if (1 !== preg_match('/\$'.$variable.'\s*=\s*array\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)/', $code, $m)) {
        return '';
    }

    return $m[1].'.'.$m[2];
};

$ranges = [];
$previous = null;
foreach ($tags as $tag) {
    $code = $git(['show', $tag.':htdocs/install/check.php']);
    if ('' === $code) {
        fwrite(STDERR, "warning: no htdocs/install/check.php in {$tag}, skipped\n");
        continue;
    }
    $values = [
        'min' => $read($code, 'arrayphpminversionerror'),
        'recommended' => $read($code, 'arrayphpminversionwarning'),
        'max' => $read($code, 'arrayphpmaxversionwarning'),
    ];
    if ('' === $values['min']) {
        fwrite(STDERR, "warning: no PHP minimum found in {$tag}/htdocs/install/check.php, skipped\n");
        continue;
    }
    if ($values !== $previous) {
        $ranges[$tag] = $values;
        $previous = $values;
    }
}

$lines = '';
foreach ($ranges as $since => $values) {
    $lines .= sprintf("        '%s' => ['min' => '%s', 'recommended' => '%s', 'max' => '%s'],\n", $since, $values['min'], $values['recommended'], $values['max']);
}
$head = trim($git(['log', '-1', '--format=%cs', '--all']));

$php = <<<PHP
    <?php

    namespace Dolicli\\Php;

    /**
     * PHP range declared by htdocs/install/check.php of each Dolibarr version (first version of
     * each range => values). Generated by build/generate-php-matrix.php from the Dolibarr sources
     * ({$head}): do not edit by hand. Real maximums observed are in ObservedMatrix.
     */
    final class DeclaredMatrix
    {
        const RANGES = [
    {$lines}    ];
    }

    PHP;

if (false === file_put_contents($target, $php)) {
    fwrite(STDERR, "Cannot write {$target}\n");
    exit(1);
}
fwrite(STDOUT, count($ranges)." ranges from ".count($tags)." versions written to {$target}\n");
