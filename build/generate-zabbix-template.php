<?php

declare(strict_types=1);

/*
 * Generate contrib/zabbix/dolicli_template.yaml (Zabbix 7.0 export format) from the checks
 * and metrics of the server code, so the template follows the state file.
 *
 *   php build/generate-zabbix-template.php
 */

require dirname(__DIR__).'/vendor/autoload.php';

use Dolicli\Monitor\Collector;
use Dolicli\Monitor\Formats;

const TEMPLATE = 'Dolibarr by dolicli';
const MASTER = 'vfs.file.contents[{#STATEFILE}]';

function uuid(string $name): string
{
    return md5('dolicli-zabbix-'.$name);
}

function quote(string $value): string
{
    return "'".str_replace("'", "''", $value)."'";
}

$statusMap = 'return {"ok": 0, "warning": 1, "critical": 2, "unknown": 3, "skipped": 0}[value];';
$checks = array_merge(Collector::fastChecks(), Collector::slowChecks());
sort($checks);

$items = [];
$items[] = [
    'name' => 'Dolibarr {#INSTANCE}: state file',
    'key' => MASTER,
    'yaml' => "              delay: 1m\n              history: '0'\n              value_type: TEXT\n              trends: '0'\n"
        ."              description: 'Raw state file written by dolicli monitor collect (schema/state.schema.json).'\n",
];
$items[] = [
    'name' => 'Dolibarr {#INSTANCE}: status',
    'key' => 'dolicli.status[{#INSTANCE}]',
    'dependent' => true,
    'preprocessing' => [['JSONPATH', '$.status'], ['JAVASCRIPT', $statusMap]],
    'yaml' => "              valuemap:\n                name: 'dolicli status'\n              description: 'Most serious status of the checks: 0 ok, 1 warning, 2 critical, 3 unknown.'\n",
];
$items[] = [
    'name' => 'Dolibarr {#INSTANCE}: collection age',
    'key' => 'dolicli.collector.age[{#INSTANCE}]',
    'dependent' => true,
    'preprocessing' => [['JSONPATH', '$.generated_at_unix'], ['JAVASCRIPT', 'return Math.floor(Date.now() / 1000) - value;']],
    'yaml' => "              units: s\n              description: 'Seconds since the last write of the state file (collector.age is never stored).'\n",
];
foreach ($checks as $check) {
    $items[] = [
        'name' => 'Dolibarr {#INSTANCE}: '.$check.' status',
        'key' => 'dolicli.check.status[{#INSTANCE},'.$check.']',
        'dependent' => true,
        'preprocessing' => [['JSONPATH', '$.checks["'.$check.'"].status', 'CUSTOM_VALUE', 'unknown'], ['JAVASCRIPT', $statusMap]],
        'yaml' => "              valuemap:\n                name: 'dolicli status'\n",
    ];
    if (isset(Formats::METRICS[$check])) {
        $unit = Formats::METRICS[$check][2];
        $items[] = [
            'name' => 'Dolibarr {#INSTANCE}: '.$check,
            'key' => 'dolicli.check.value[{#INSTANCE},'.$check.']',
            'dependent' => true,
            'preprocessing' => [
                ['JSONPATH', '$.checks["'.$check.'"].value', 'DISCARD_VALUE', ''],
                ['JAVASCRIPT', "if (value === 'null' || value === '') { throw 'no value'; } return value === 'true' ? 1 : (value === 'false' ? 0 : value);", 'DISCARD_VALUE', ''],
            ],
            'yaml' => ('' !== $unit ? "              units: {$unit}\n" : '')
                ."              value_type: FLOAT\n              description: ".quote(Formats::METRICS[$check][1])."\n",
        ];
    }
}

$yaml = "zabbix_export:\n  version: '7.0'\n  template_groups:\n    - uuid: ".uuid('group')."\n      name: Templates/Applications\n"
    ."  templates:\n    - uuid: ".uuid('template')."\n      template: ".quote(TEMPLATE)."\n      name: ".quote(TEMPLATE)."\n"
    ."      description: 'Dolibarr instances monitored by dolicli: reads the state files /var/lib/dolicli/<run_as>/<instance>.json. Generated by build/generate-zabbix-template.php.'\n"
    ."      groups:\n        - name: Templates/Applications\n"
    ."      discovery_rules:\n        - uuid: ".uuid('discovery')."\n          name: 'Dolibarr instances'\n          key: dolicli.discover\n          delay: 1h\n"
    ."          lifetime: 7d\n          description: 'UserParameter=dolicli.discover,<php of the instances> /usr/local/bin/dolicli monitor discover'\n"
    ."          item_prototypes:\n";
foreach ($items as $item) {
    $yaml .= '            - uuid: '.uuid($item['key'])."\n              name: ".quote($item['name'])."\n";
    if ( ! empty($item['dependent'])) {
        $yaml .= "              type: DEPENDENT\n";
    }
    $yaml .= '              key: '.quote($item['key'])."\n";
    if ( ! empty($item['dependent'])) {
        $yaml .= "              delay: '0'\n";
    }
    $yaml .= $item['yaml'];
    if (isset($item['preprocessing'])) {
        $yaml .= "              preprocessing:\n";
        foreach ($item['preprocessing'] as $step) {
            $yaml .= '                - type: '.$step[0]."\n";
            $yaml .= "                  parameters:\n                    - ".quote($step[1])."\n";
            if (isset($step[2])) {
                $yaml .= '                  error_handler: '.$step[2]."\n";
                if ('' !== $step[3]) {
                    $yaml .= '                  error_handler_params: '.quote($step[3])."\n";
                }
            }
        }
    }
    if ( ! empty($item['dependent'])) {
        $yaml .= "              master_item:\n                key: ".quote(MASTER)."\n";
    }
    $yaml .= "              tags:\n                - tag: component\n                  value: dolibarr\n";
}

$triggers = [
    ['last(/'.TEMPLATE.'/dolicli.status[{#INSTANCE}])=2', 'Dolibarr {#INSTANCE} is critical', 'HIGH'],
    ['last(/'.TEMPLATE.'/dolicli.status[{#INSTANCE}])=3', 'Dolibarr {#INSTANCE}: state unknown', 'AVERAGE'],
    ['last(/'.TEMPLATE.'/dolicli.status[{#INSTANCE}])=1', 'Dolibarr {#INSTANCE} has warnings', 'WARNING'],
    ['last(/'.TEMPLATE.'/dolicli.collector.age[{#INSTANCE}])>{$DOLICLI.COLLECT.MAX_AGE}', 'Dolibarr {#INSTANCE}: collection stopped', 'HIGH'],
    ['nodata(/'.TEMPLATE.'/'.MASTER.',15m)=1', 'Dolibarr {#INSTANCE}: state file not read', 'HIGH'],
];
$yaml .= "          trigger_prototypes:\n";
foreach ($triggers as $trigger) {
    $yaml .= '            - uuid: '.uuid($trigger[1])."\n              expression: ".quote($trigger[0])."\n              name: ".quote($trigger[1])
        ."\n              priority: {$trigger[2]}\n              tags:\n                - tag: component\n                  value: dolibarr\n";
}
$yaml .= "      macros:\n        - macro: '{\$DOLICLI.COLLECT.MAX_AGE}'\n          value: '900'\n"
    ."          description: 'Age of the state file (s) beyond which the collection is considered stopped: three times the fast interval.'\n"
    ."      valuemaps:\n        - uuid: ".uuid('valuemap')."\n          name: 'dolicli status'\n          mappings:\n";
foreach (['0' => 'ok', '1' => 'warning', '2' => 'critical', '3' => 'unknown'] as $value => $label) {
    $yaml .= "            - value: '{$value}'\n              newvalue: {$label}\n";
}

$target = dirname(__DIR__).'/contrib/zabbix/dolicli_template.yaml';
if ( ! is_dir(dirname($target)) && ! mkdir(dirname($target), 0755, true)) {
    fwrite(STDERR, "Cannot create ".dirname($target)."\n");
    exit(1);
}
if (false === file_put_contents($target, $yaml)) {
    fwrite(STDERR, "Cannot write {$target}\n");
    exit(1);
}
fwrite(STDOUT, count($items).' item prototypes, '.count($triggers)." trigger prototypes written to {$target}\n");
